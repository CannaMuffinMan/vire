def pack() -> None:
    a = Asm()
    emit_https(a)
    emit_load(a)
    emit_b64(a)
    emit_serve(a)
    emit_hs(a)
    emit_recv(a)
    emit_send(a)
    emit_strings(a)
    a.finish()
    idx = {n: i for i, n in enumerate(NAMES)}
    miss = [n for n in list(a.labels) + [n for _, n in a.fixes] if n not in idx]
    if miss:
        raise SystemExit("missing " + ",".join(sorted(set(miss))))
    pins = "".join(struct.pack("<I", off).hex() + struct.pack("<H", idx[n]).hex() for n, off in a.labels.items())
    fixes = "".join(struct.pack("<I", off).hex() + struct.pack("<H", idx[n]).hex() for off, n in a.fixes)
    (SRC / "rt-tls-blob.txt").write_text(a.b.hex() + "\n")
    (SRC / "rt-tls-pins.txt").write_text(pins + "\n")
    (SRC / "rt-tls-fixes.txt").write_text(fixes + "\n")
    (SRC / "rt-tls-names.txt").write_text(",".join(NAMES) + "\n")
    print("tls_names =", NAMES)
    print("blob", len(a.b), "pins", len(a.labels), "fixes", len(a.fixes))



class Asm:
    def __init__(self) -> None:
        self.b = bytearray()
        self.labels: dict[str, int] = {}
        self.fixes: list[tuple[int, str]] = []
        self.patches: list[tuple[int, str]] = []

    def pin(self, name: str) -> None:
        self.labels[name] = len(self.b)

    def raw(self, *xs: int) -> None:
        self.b.extend(int(x) & 255 for x in xs)

    def u32(self, n: int) -> None:
        self.b.extend(struct.pack("<I", n & 0xFFFFFFFF))

    def rel32(self, name: str) -> None:
        self.fixes.append((len(self.b), name))
        self.u32(0)

    def call(self, name: str) -> None:
        self.raw(0xE8)
        self.rel32(name)

    def jmp(self, name: str) -> None:
        self.raw(0xE9)
        self.rel32(name)

    def jcc(self, op: int, name: str) -> None:
        self.raw(0x0F, op)
        self.rel32(name)

    def call_iat(self, name: str) -> None:
        self.raw(0xFF, 0x15)
        self.rel32(name)

    def lea(self, reg: str, name: str) -> None:
        codes = {"rax": 0x05, "rcx": 0x0D, "rdx": 0x15, "r8": None, "r9": None}
        if reg == "r8":
            self.raw(0x4C, 0x8D, 0x05)
        elif reg == "r9":
            self.raw(0x4C, 0x8D, 0x0D)
        else:
            self.raw(0x48, 0x8D, codes[reg])
        self.rel32(name)

    def pro(self, n: int = 0x120) -> None:
        self.raw(0x55, 0x48, 0x89, 0xE5, 0x48, 0x81, 0xEC)
        self.u32(n)

    def epi(self) -> None:
        self.raw(0xC9, 0xC3)

    def sayz(self, name: str, n: int) -> None:
        self.raw(0xB9, 0xF5, 0xFF, 0xFF, 0xFF)
        self.call_iat("iat_gs")
        self.raw(0x48, 0x89, 0xC1)
        self.lea("rdx", name)
        self.raw(0x48, 0x83, 0xC2, 0x08, 0x41, 0xB8, n, 0, 0, 0)
        self.raw(0x4C, 0x8D, 0x4D, 0xA8, 0x48, 0xC7, 0x44, 0x24, 0x20, 0, 0, 0, 0)
        self.call_iat("iat_wf")

    def ljcc(self, op: int, name: str) -> None:
        self.raw(0x0F, op)
        self.patches.append((len(self.b), name))
        self.u32(0)

    def ljmp(self, name: str) -> None:
        self.raw(0xE9)
        self.patches.append((len(self.b), name))
        self.u32(0)

    def finish(self) -> None:
        for at, name in self.patches:
            rel = self.labels[name] - (at + 4)
            self.b[at : at + 4] = struct.pack("<i", rel)


def pop_text(a: Asm, dest: int) -> None:
    a.raw(0x49, 0x83, 0xED, 0x10, 0x49, 0x8B, 0x45, 0x00, 0x49, 0x8B, 0x55, 0x08)
    a.raw(0x48, 0x83, 0xF8, 0x02)
    a.jcc(0x85, "https_bad")
    a.raw(0x48, 0x89, 0x55, dest)


def emit_https(a: Asm) -> None:
    a.pin("rt_https")
    a.pro()
    pop_text(a, 0xF0)
    pop_text(a, 0xE8)
    a.raw(0x49, 0x83, 0xED, 0x10, 0x49, 0x8B, 0x45, 0x00, 0x49, 0x8B, 0x55, 0x08)
    a.raw(0x48, 0x83, 0xF8, 0x01)
    a.jcc(0x85, "https_bad")
    a.raw(0x48, 0x89, 0x55, 0xE0)
    a.lea("rax", "rt_tls_recv")
    a.lea("rcx", "tls_recv_slot")
    a.raw(0x48, 0x89, 0x01)
    a.lea("rax", "rt_tls_send")
    a.lea("rcx", "tls_send_slot")
    a.raw(0x48, 0x89, 0x01)
    a.raw(0x48, 0x8B, 0x4D, 0xE8, 0x48, 0x8B, 0x55, 0xF0)
    a.call("rt_tls_load")
    a.raw(0x48, 0x85, 0xC0)
    a.jcc(0x84, "https_tlsfail")
    a.raw(0x49, 0xC7, 0x45, 0x00, 1, 0, 0, 0)
    a.raw(0x48, 0x8B, 0x45, 0xE0, 0x49, 0x89, 0x45, 0x08, 0x49, 0x83, 0xC5, 0x10)
    a.raw(0xC9)
    a.jmp("rt_listen")
    a.pin("https_bad")
    a.lea("rcx", "msg_https")
    a.call("rt_fail")
    a.pin("https_tlsfail")
    a.lea("rcx", "msg_tls")
    a.call("rt_fail")


def emit_load(a: Asm) -> None:
    a.pin("rt_tls_load")
    a.pro()
    a.raw(0x48, 0x89, 0x4D, 0xF8, 0x48, 0x89, 0x55, 0xF0)
    a.call("rt_net_init")
    a.raw(0x49, 0xC7, 0x45, 0x00, 2, 0, 0, 0)
    a.raw(0x48, 0x8B, 0x45, 0xF8, 0x49, 0x89, 0x45, 0x08, 0x49, 0x83, 0xC5, 0x10)
    a.call("rt_read")
    a.raw(0x49, 0x83, 0xED, 0x10, 0x49, 0x8B, 0x45, 0x00, 0x49, 0x8B, 0x55, 0x08)
    a.raw(0x48, 0x83, 0xF8, 0x02)
    a.jcc(0x85, "die_tls")
    a.raw(0x48, 0x89, 0x55, 0xE8)
    a.raw(0x49, 0xC7, 0x45, 0x00, 2, 0, 0, 0)
    a.raw(0x48, 0x8B, 0x45, 0xF0, 0x49, 0x89, 0x45, 0x08, 0x49, 0x83, 0xC5, 0x10)
    a.call("rt_read")
    a.raw(0x49, 0x83, 0xED, 0x10, 0x49, 0x8B, 0x45, 0x00, 0x49, 0x8B, 0x55, 0x08)
    a.raw(0x48, 0x83, 0xF8, 0x02)
    a.jcc(0x85, "die_tls")
    a.raw(0x48, 0x89, 0x55, 0xE0)
    a.raw(0x48, 0x8B, 0x4D, 0xE8)
    a.call("rt_tls_b64")
    a.raw(0x48, 0x85, 0xC0)
    a.jcc(0x84, "die_b64")
    a.raw(0x48, 0x89, 0x45, 0xD8, 0x48, 0x89, 0x55, 0xD0)
    a.raw(0xB9, 1, 0, 0, 0, 0x48, 0x8B, 0x55, 0xD8, 0x4C, 0x8B, 0x45, 0xD0)
    a.call_iat("iat_ccc")
    a.raw(0x48, 0x85, 0xC0)
    a.jcc(0x84, "die_cert")
    a.raw(0x48, 0x89, 0x45, 0xC8)
    a.lea("rcx", "tls_state")
    a.raw(0x48, 0x89, 0x81)
    a.u32(CERT)
    # Prefer CurrentUser\My store cert (has the CNG private key from
    # New-SelfSignedCertificate). File PKCS8 alone is SEC_E_NO_CREDENTIALS.
    a.raw(0xB9, 10, 0, 0, 0)
    a.raw(0x31, 0xD2, 0x45, 0x31, 0xC0, 0x41, 0xB9)
    a.u32(0x00010000)
    a.lea("rax", "txt_my")
    a.raw(0x48, 0x89, 0x44, 0x24, 0x20)
    a.call_iat("iat_cos")
    a.raw(0x48, 0x85, 0xC0)
    a.jcc(0x84, "die_cert")
    a.raw(0x48, 0x89, 0xC1, 0xBA, 1, 0, 0, 0, 0x45, 0x31, 0xC0, 0x41, 0xB9)
    a.u32(0x000D0000)
    a.raw(0x48, 0x8B, 0x45, 0xC8, 0x48, 0x89, 0x44, 0x24, 0x20)
    a.raw(0x48, 0xC7, 0x44, 0x24, 0x28, 0, 0, 0, 0)
    a.call_iat("iat_cfd")
    a.raw(0x48, 0x85, 0xC0)
    a.jcc(0x84, "die_cert")
    a.raw(0x48, 0x89, 0x45, 0xC8)
    a.lea("rcx", "tls_state")
    a.raw(0x48, 0x89, 0x81)
    a.u32(CERT)
    a.raw(0x48, 0x8D, 0x4D, 0x80, 0x31, 0xC0, 0xB2, 0x50)
    a.pin("zero_cred")
    a.raw(0x88, 0x01, 0x48, 0xFF, 0xC1, 0xFE, 0xCA, 0x75, 0xF7)
    # SCHANNEL_CRED v4 x64: paCred@8, min cipher@56, dwFlags@68, dwCredFormat@72.
    a.raw(0xC7, 0x45, 0x80, SCHANNEL_CRED_VERSION, 0, 0, 0)
    a.raw(0xC7, 0x45, 0x84, 1, 0, 0, 0)
    a.lea("rax", "tls_state")
    a.raw(0x48, 0x8D, 0x80)
    a.u32(CERT)
    a.raw(0x48, 0x89, 0x45, 0x88)
    a.raw(0xC7, 0x45, 0xC4)
    a.u32(SCH_FLAGS)
    a.raw(0x31, 0xC9)
    a.lea("rdx", "txt_unisp")
    a.raw(0x41, 0xB8, 1, 0, 0, 0, 0x45, 0x31, 0xC9)
    a.raw(0x48, 0x8D, 0x45, 0x80, 0x48, 0x89, 0x44, 0x24, 0x20)
    a.raw(0x48, 0xC7, 0x44, 0x24, 0x28, 0, 0, 0, 0)
    a.raw(0x48, 0xC7, 0x44, 0x24, 0x30, 0, 0, 0, 0)
    a.lea("rax", "tls_state")
    a.raw(0x48, 0x8D, 0x80)
    a.u32(CRED)
    a.raw(0x48, 0x89, 0x44, 0x24, 0x38)
    a.lea("rax", "tls_state")
    a.raw(0x48, 0x8D, 0x80)
    a.u32(EXPIRY)
    a.raw(0x48, 0x89, 0x44, 0x24, 0x40)
    a.call_iat("iat_ach")
    a.raw(0x85, 0xC0)
    a.jcc(0x85, "die_ach")
    # Byte buffers live in PE BSS, not the GC heap. rt_alloc objects are
    # unmarked from tls_state, so the first client alloc compacted them.
    a.lea("rax", "tls_scratch")
    a.lea("rcx", "tls_state")
    a.raw(0x48, 0x89, 0x81)
    a.u32(SCRATCH)
    a.lea("rax", "tls_enc")
    a.lea("rcx", "tls_state")
    a.raw(0x48, 0x89, 0x81)
    a.u32(ENC)
    a.lea("rax", "tls_plain")
    a.lea("rcx", "tls_state")
    a.raw(0x48, 0x89, 0x81)
    a.u32(PLAIN)
    a.lea("rcx", "tls_state")
    a.raw(0xC7, 0x81)
    a.u32(ENCCAP)
    a.u32(32768)
    a.raw(0xB8, 1, 0, 0, 0)
    a.epi()
    a.pin("load_fail")
    a.raw(0x31, 0xC0)
    a.epi()
    for name, msg in (
        ("die_tls", "msg_tls"),
        ("die_b64", "msg_tls_b64"),
        ("die_cert", "msg_tls_cert"),
        ("die_prov", "msg_tls_prov"),
        ("die_key", "msg_tls_key"),
        ("die_prop", "msg_tls_prop"),
    ):
        a.pin(name)
        a.lea("rcx", msg)
        a.call("rt_fail")
    a.pin("die_ach")
    a.raw(0x89, 0xC6)
    a.lea("rax", "msg_tls_ach")
    a.raw(0x48, 0x8D, 0x78, 16)
    a.lea("r8", "txt_hex")
    a.raw(0xB9, 8, 0, 0, 0)
    a.pin("ach_hex")
    a.raw(0xC1, 0xC6, 4, 0x89, 0xF0, 0x83, 0xE0, 15)
    a.raw(0x41, 0x8A, 0x04, 0x00, 0xAA, 0xE2, 0xF1)
    a.lea("rcx", "msg_tls_ach")
    a.call("rt_fail")



def emit_serve(a: Asm) -> None:
    a.pin("rt_tls_serve")
    a.pro()
    a.raw(0x48, 0x89, 0x4D, 0xF8)
    a.lea("rax", "rt_tls_recv")
    a.lea("rcx", "tls_recv_slot")
    a.raw(0x48, 0x89, 0x01)
    a.lea("rax", "rt_tls_send")
    a.lea("rcx", "tls_send_slot")
    a.raw(0x48, 0x89, 0x01)
    a.raw(0x48, 0x8B, 0x4D, 0xF8)
    a.lea("rax", "tls_state")
    a.raw(0x48, 0x89, 0x88)
    a.u32(SOCK)
    a.raw(0x48, 0xC7, 0x80)
    a.u32(CTXSET)
    a.u32(0)
    a.raw(0x48, 0xC7, 0x80)
    a.u32(ENCLEN)
    a.u32(0)
    a.call("rt_tls_hs")
    a.raw(0x48, 0x85, 0xC0)
    a.jcc(0x84, "serve_hsfail")
    a.sayz("msg_hs_ok", 16)
    a.ljmp("serve_go")
    a.pin("serve_hsfail")
    a.sayz("msg_hs_fail", 18)
    a.ljmp("serve_done")
    a.pin("serve_go")
    a.lea("rcx", "tls_state")
    a.raw(0x48, 0xC7, 0x01, 1, 0, 0, 0)
    a.raw(0x48, 0x8B, 0x4D, 0xF8)

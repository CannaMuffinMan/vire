def parse_u16(s, i):
    return int(s[i : i + 2], 16) + int(s[i + 2 : i + 4], 16) * 256


def parse_u32(s, i):
    return parse_u16(s, i) + parse_u16(s, i + 4) * 65536


def pack_u16(n):
    return bytes([n & 255, (n >> 8) & 255])


def pack_u32(n):
    return pack_u16(n & 65535) + pack_u16((n >> 16) & 65535)


def pack_rec(off, idn):
    return pack_u32(off) + pack_u16(idn)


def load_names():
    text = (SRC / "rt-net.vire").read_text()
    start = text.find("return [")
    end = text.find("]", start)
    return [x.strip().strip('"') for x in text[start + 8 : end].split(",") if x.strip()]


class Asm:
    def __init__(self, base):
        self.base = base
        self.buf = bytearray()
        self.labels = {}
        self.fixups = []

    def here(self):
        return self.base + len(self.buf)

    def pin(self, name):
        self.labels[name] = self.here()

    def emit(self, *xs):
        for x in xs:
            if isinstance(x, (bytes, bytearray, list, tuple)):
                self.buf.extend(x)
            else:
                self.buf.append(x)

    def rel32(self, name):
        self.fixups.append((self.here(), name))
        self.emit(0, 0, 0, 0)

    def call(self, name):
        self.emit(0xE8)
        self.rel32(name)

    def jmp(self, name):
        self.emit(0xE9)
        self.rel32(name)

    def jcc(self, cc, name):
        self.emit(0x0F, cc)
        self.rel32(name)

    def lea_rdx(self, name):
        self.emit(0x48, 0x8D, 0x15)
        self.rel32(name)

    def lea_rcx(self, name):
        self.emit(0x48, 0x8D, 0x0D)
        self.rel32(name)

    def iat(self, name):
        self.emit(0xFF, 0x15)
        self.rel32(name)



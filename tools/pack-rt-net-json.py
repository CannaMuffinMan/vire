def load_names():
    text = (SRC / "rt-net.vire").read_text()
    start = text.find("return [")
    end = text.find("]", start)
    return [x.strip().strip('"') for x in text[start + 8 : end].split(",") if x.strip()]


def resolve_locals(a):
    blob = bytearray(a.image)
    kept = []
    for at, n in a.fixes:
        if n.startswith("_"):
            if n not in a.labels:
                raise SystemExit("unresolved local " + n)
            rel = (a.labels[n] - (at + 4)) & 0xFFFFFFFF
            blob[at : at + 4] = u32(rel)
        else:
            kept.append((at, n))
    a.image = blob
    a.fixes = kept


def write_packed(a, names):
    idx = {n: i for i, n in enumerate(names)}
    missing = []
    for n in a.labels:
        if n.startswith("_"):
            continue
        if n not in idx:
            missing.append("pin:" + n)
    for at, n in a.fixes:
        if n not in idx:
            missing.append("fix:" + n)
    if missing:
        raise SystemExit("names missing: " + ", ".join(sorted(set(missing))))
    pin_raw = b"".join(u32(off) + u16(idx[n]) for n, off in a.labels.items() if not n.startswith("_"))
    fix_raw = b"".join(u32(at) + u16(idx[n]) for at, n in a.fixes)
    hx = bytes(a.image).hex()
    for dest in (SRC, ROOT / "data" / "src"):
        dest.mkdir(parents=True, exist_ok=True)
        (dest / "rt-net-json-blob.txt").write_text(hx + "\n")
        (dest / "rt-net-json-pins.txt").write_text(pin_raw.hex() + "\n")
        (dest / "rt-net-json-fixes.txt").write_text(fix_raw.hex() + "\n")
    print(
        "blob_bytes",
        len(a.image),
        "pins",
        len(pin_raw) // 6,
        "fixes",
        len(a.fixes),
        "park_guard",
        "4d8d5510" in hx,
        "colon",
        "4889c1b23a" in hx,
        "cursor",
        "4c8b024c01c148894808" in hx,
        "starts",
        hx[:8],
        "old_add",
        "4801c848894108" in hx,
    )


def main():
    names = load_names()
    if "park_full" not in names:
        raise SystemExit("netNames must include park_full")
    a = Asm()
    emit_all(a)
    resolve_locals(a)
    write_packed(a, names)


if __name__ == "__main__":
    main()

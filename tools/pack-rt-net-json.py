#!/usr/bin/env python3
"""Regenerate packed native JSON encode/parse (itemCap-safe).

Live heap roots sit in rbp (encode: value @-0x10, buffer @-0x20; parse:
cursor @-8, text @-0x10). Native GC does not walk rbp. This packer parks
those slots on the VM stack (tag 2, same bytes as emitParkSlot) across
helper calls and reloads rbp from the unparked roots.

Local park branch labels are resolved in this script. Caps stay arena
33554432, list 100000, steps 5000000, compiler itemCap 1e6.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"


def u32(n):
    n = int(n) & 0xFFFFFFFF
    return bytes((n & 255, (n >> 8) & 255, (n >> 16) & 255, (n >> 24) & 255))


def u16(n):
    n = int(n) & 0xFFFF
    return bytes((n & 255, (n >> 8) & 255))


class Asm:
    def __init__(self):
        self.image = bytearray()
        self.fixes = []
        self.labels = {}
        self.seq = 0

    def here(self):
        return len(self.image)

    def pin(self, name):
        self.labels[name] = self.here()

    def tmp(self, p="L"):
        self.seq += 1
        return "_%s%d" % (p, self.seq)

    def emit(self, *xs):
        for x in xs:
            if isinstance(x, (bytes, bytearray)):
                self.image.extend(x)
            elif isinstance(x, (list, tuple)):
                self.image.extend(int(b) & 255 for b in x)
            else:
                self.image.append(int(x) & 255)

    def rel32(self, name):
        self.fixes.append((self.here(), name))
        self.emit(0, 0, 0, 0)

    def call(self, name):
        self.emit(0xE8)
        self.rel32(name)

    def jmp(self, name):
        self.emit(0xE9)
        self.rel32(name)

    def jcc(self, cc, name):
        self.emit(0x0F, cc)
        self.rel32(name)

    def lea_rcx(self, name):
        self.emit(0x48, 0x8D, 0x0D)
        self.rel32(name)

    def lea_rdx(self, name):
        self.emit(0x48, 0x8D, 0x15)
        self.rel32(name)

    def fail(self, name):
        self.lea_rcx(name)
        self.call("rt_fail")

    def pro(self):
        self.emit(0x55, 0x48, 0x89, 0xE5, 0x48, 0x81, 0xEC, 0x80, 0, 0, 0)

    def epi(self):
        self.emit(0xC9, 0xC3)

    def park_rcx(self):
        self.emit(0x4D, 0x8D, 0x55, 0x10, 0x4D, 0x8D, 0x9F)
        self.emit(u32(327680))
        self.emit(0x4D, 0x39, 0xDA, 0x0F, 0x83)
        self.rel32("park_full")
        self.emit(0x49, 0xC7, 0x45, 0x00)
        self.emit(u32(2))
        self.emit(0x49, 0x89, 0x4D, 0x08, 0x49, 0x83, 0xC5, 0x10)

    def unpark_rcx(self):
        self.emit(0x49, 0x83, 0xED, 0x10, 0x49, 0x8B, 0x4D, 0x08)

    def park_slot(self, disp):
        self.emit(0x48, 0x8B, 0x4D, disp & 255)
        self.park_rcx()

    def unpark_slot(self, disp):
        self.unpark_rcx()
        self.emit(0x48, 0x89, 0x4D, disp & 255)

    def park_enc(self):
        pe, ps = self.tmp("pe"), self.tmp("ps")
        self.park_slot(0xE0)
        self.emit(0x48, 0x8B, 0x45, 0xF8)
        self.emit(0x48, 0x83, 0xF8, 0x02)
        self.jcc(0x84, pe)
        self.emit(0x48, 0x83, 0xF8, 0x04)
        self.jcc(0x84, pe)
        self.emit(0x48, 0x83, 0xF8, 0x05)
        self.jcc(0x84, pe)
        self.jmp(ps)
        self.pin(pe)
        self.park_slot(0xF0)
        self.pin(ps)

    def unpark_enc(self):
        ue, us = self.tmp("ue"), self.tmp("us")
        self.emit(0x4C, 0x8B, 0x4D, 0xF8)
        self.emit(0x49, 0x83, 0xF9, 0x02)
        self.jcc(0x84, ue)
        self.emit(0x49, 0x83, 0xF9, 0x04)
        self.jcc(0x84, ue)
        self.emit(0x49, 0x83, 0xF9, 0x05)
        self.jcc(0x84, ue)
        self.jmp(us)
        self.pin(ue)
        self.unpark_slot(0xF0)
        self.pin(us)
        self.unpark_slot(0xE0)

    def call_buf_byte_imm(self, byte):
        self.park_enc()
        self.emit(0x48, 0x8B, 0x4D, 0xE0, 0xBA)
        self.emit(u32(byte))
        self.call("rt_buf_byte")
        self.unpark_enc()
        self.emit(0x48, 0x89, 0x45, 0xE0)

    def call_buf_byte_dl(self):
        self.park_enc()
        self.emit(0x48, 0x8B, 0x4D, 0xE0)
        self.call("rt_buf_byte")
        self.unpark_enc()
        self.emit(0x48, 0x89, 0x45, 0xE0)

    def rebuild_cursor(self):
        """cursor.ptr = text+8+off ; cursor.end = text+8+len. text @ [rbp-0x18], off @ [rbp-0x28]."""
        self.emit(0x48, 0x8B, 0x55, 0xE8)
        self.emit(0x48, 0x8B, 0x45, 0xF8)
        self.emit(0x48, 0x8D, 0x4A, 0x08)
        self.emit(0x48, 0x03, 0x4D, 0xD8)
        self.emit(0x48, 0x89, 0x08)
        self.emit(0x4C, 0x8B, 0x02)
        self.emit(0x48, 0x8D, 0x4A, 0x08)
        self.emit(0x4C, 0x01, 0xC1)
        self.emit(0x48, 0x89, 0x48, 0x08)

    def snap_off(self):
        self.emit(0x48, 0x8B, 0x45, 0xF8, 0x48, 0x8B, 0x08)
        self.emit(0x48, 0x8B, 0x55, 0xE8, 0x48, 0x8D, 0x52, 0x08)
        self.emit(0x48, 0x29, 0xD1, 0x48, 0x89, 0x4D, 0xD8)

    def park_parse(self, with_buf=False):
        self.snap_off()
        self.park_slot(0xF8)
        self.park_slot(0xE8)
        if with_buf:
            self.park_slot(0xE0)

    def unpark_parse(self, with_buf=False, rebuild=True):
        self.emit(0x49, 0x89, 0xC3)
        if with_buf:
            self.unpark_slot(0xE0)
        self.unpark_slot(0xE8)
        self.unpark_slot(0xF8)
        if rebuild:
            self.rebuild_cursor()
        self.emit(0x4C, 0x89, 0xD8)

    def pop_pair(self, tag_d, pay_d):
        self.emit(0x49, 0x83, 0xED, 0x10)
        self.emit(0x49, 0x8B, 0x45, 0x00, 0x49, 0x8B, 0x55, 0x08)
        self.emit(0x48, 0x89, 0x45, tag_d & 255)
        self.emit(0x48, 0x89, 0x55, pay_d & 255)

    def push_pair(self, tag_d, pay_d):
        self.emit(0x48, 0x8B, 0x45, tag_d & 255)
        self.emit(0x48, 0x8B, 0x55, pay_d & 255)
        self.emit(0x49, 0x89, 0x45, 0x00, 0x49, 0x89, 0x55, 0x08)
        self.emit(0x49, 0x83, 0xC5, 0x10)

    def call_pushing(self, name):
        self.park_parse(False)
        self.call(name)
        self.pop_pair(0xB8, 0xB0)
        self.unpark_parse(False)
        self.push_pair(0xB8, 0xB0)

    def call_json_val(self):
        self.park_parse(False)
        self.emit(0x48, 0x8B, 0x4D, 0xF8, 0x48, 0x8B, 0x55, 0xF0, 0x48, 0xFF, 0xC2, 0x4C, 0x8B, 0x45, 0xE8)
        self.call("rt_json_val")
        self.pop_pair(0xB8, 0xB0)
        self.unpark_parse(False, False)
        self.push_pair(0xB8, 0xB0)


